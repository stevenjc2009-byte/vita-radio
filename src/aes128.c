static const unsigned char RCON[10] = {
    0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36
};

/* Multiply in GF(2^8) modulo x^8 + x^4 + x^3 + x + 1. */
static unsigned char gmul(unsigned char a, unsigned char b)
{
    unsigned char p = 0;
    int i;

    for (i = 0; i < 8; i++) {
        if (b & 1)
            p ^= a;
        a = (unsigned char)((a << 1) ^ ((a & 0x80) ? 0x1b : 0x00));
        b = (unsigned char)(b >> 1);
    }
    return p;
}

void aes128_init(Aes128 *a, const unsigned char key[16])
{
    int i, j;

    memcpy(a->rk, key, 16);
    for (i = 4; i < 44; i++) {
        unsigned char t[4];

        memcpy(t, a->rk + (i - 1) * 4, 4);
        if (i % 4 == 0) {
            unsigned char first = t[0];
            t[0] = (unsigned char)(SBOX[t[1]] ^ RCON[i / 4 - 1]);
            t[1] = SBOX[t[2]];
            t[2] = SBOX[t[3]];
            t[3] = SBOX[first];
        }
        for (j = 0; j < 4; j++)
            a->rk[i * 4 + j] = (unsigned char)(a->rk[(i - 4) * 4 + j] ^ t[j]);
    }
}

/* The state is column major: byte r + 4c is row r of column c. */
static void inv_shift_rows(unsigned char s[16])
{
    unsigned char t[16];
    int r, c;

    for (r = 0; r < 4; r++)
        for (c = 0; c < 4; c++)
            t[r + 4 * ((c + r) & 3)] = s[r + 4 * c];
    memcpy(s, t, 16);
}

static void inv_sub_bytes(unsigned char s[16])
{
    int i;

    for (i = 0; i < 16; i++)
        s[i] = INV_SBOX[s[i]];
}

static void add_round_key(unsigned char s[16], const unsigned char *rk)
{
    int i;

    for (i = 0; i < 16; i++)
        s[i] = (unsigned char)(s[i] ^ rk[i]);
}

static void inv_mix_columns(unsigned char s[16])
{
    int c;

    for (c = 0; c < 4; c++) {
        unsigned char a0 = s[4 * c + 0], a1 = s[4 * c + 1];
        unsigned char a2 = s[4 * c + 2], a3 = s[4 * c + 3];

        s[4 * c + 0] = (unsigned char)(gmul(a0, 14) ^ gmul(a1, 11) ^ gmul(a2, 13) ^ gmul(a3, 9));
        s[4 * c + 1] = (unsigned char)(gmul(a0, 9) ^ gmul(a1, 14) ^ gmul(a2, 11) ^ gmul(a3, 13));
        s[4 * c + 2] = (unsigned char)(gmul(a0, 13) ^ gmul(a1, 9) ^ gmul(a2, 14) ^ gmul(a3, 11));
        s[4 * c + 3] = (unsigned char)(gmul(a0, 11) ^ gmul(a1, 13) ^ gmul(a2, 9) ^ gmul(a3, 14));
    }
}

void aes128_decrypt_block(const Aes128 *a, const unsigned char in[16],
                          unsigned char out[16])
{
    unsigned char s[16];
    int round;

    memcpy(s, in, 16);
    add_round_key(s, a->rk + 10 * 16);
    for (round = 9; round >= 1; round--) {
        inv_shift_rows(s);
        inv_sub_bytes(s);
        add_round_key(s, a->rk + round * 16);
        inv_mix_columns(s);
    }
    inv_shift_rows(s);
    inv_sub_bytes(s);
    add_round_key(s, a->rk);
    memcpy(out, s, 16);
}

int aes128_cbc_decrypt(const Aes128 *a, const unsigned char iv[16],
                       const unsigned char *in, size_t len, unsigned char *out)
{
    unsigned char prev[16], cur[16], plain[16];
    size_t off, i;

    if (a == NULL || iv == NULL || in == NULL || out == NULL)
        return -1;
    if (len == 0 || len % 16 != 0)
        return -1;

    memcpy(prev, iv, 16);
    for (off = 0; off < len; off += 16) {
        /* Copy the ciphertext block out first: in and out may be the same
         * buffer, which is how hls_crypt.c decrypts a segment in place. */
        memcpy(cur, in + off, 16);
        aes128_decrypt_block(a, cur, plain);
        for (i = 0; i < 16; i++)
            out[off + i] = (unsigned char)(plain[i] ^ prev[i]);
        memcpy(prev, cur, 16);
    }
    return 0;
}

long aes128_pkcs7_len(const unsigned char *buf, size_t len)
{
    unsigned char pad;
    size_t i;

    if (buf == NULL || len == 0)
        return -1;

    pad = buf[len - 1];
    if (pad == 0 || pad > 16)
        return -1;
    if ((size_t)pad > len)
        return -1;
    for (i = 0; i < (size_t)pad; i++)
        if (buf[len - 1 - i] != pad)
            return -1;

    return (long)(len - (size_t)pad);
}
